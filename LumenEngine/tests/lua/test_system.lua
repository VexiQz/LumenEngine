t.describe("regex", function()
  t.it("basics", function()
    t.truthy(rx.test("a+b", "xaaab")); t.falsy(rx.test("^a+b$", "xaaab"))
    t.eq({ rx.find("b+", "aabbbcc") }, { 3, 5 })
    local m = rx.match("(\\d+)-(\\d+)", "tel 555-1234 ok")
    t.eq(m.text, "555-1234"); t.eq(m[1], "555"); t.eq(m[2], "1234"); t.eq(m.start, 5)
  end)
  t.it("named groups, backrefs, alternation", function()
    local m = rx.match("(?<y>\\d{4})-(?<m>\\d\\d)", "on 2026-10-22")
    t.eq(m.named.y, "2026"); t.eq(m.named.m, "10")
    t.truthy(rx.test("(\\w)\\1", "hello")); t.falsy(rx.test("^(\\w)\\1$", "ab"))
    t.truthy(rx.test("^(?:cat|dog)s?$", "dogs"))
    t.truthy(rx.test("(?<q>['\"]).*\\k<q>", "'x'"))
  end)
  t.it("quantifiers: lazy, possessive, ranges", function()
    t.eq(rx.match("<.+?>", "<a><b>").text, "<a>")
    t.eq(rx.match("<.+>", "<a><b>").text, "<a><b>")
    t.eq(rx.match("a{2,3}", "aaaaa").text, "aaa")
    t.falsy(rx.test("a++a", "aaaa"))
    t.eq(rx.match("x{2}", "xxx").text, "xx")
    t.eq(rx.match("a{,2}", "a{,2}").text, "a{,2}")
  end)
  t.it("classes and unicode", function()
    t.eq(rx.match("[a-c]+", "xxabcabcz").text, "abcabc")
    t.eq(rx.match("[^a-c]+", "abxyzc").text, "xyz")
    t.eq(rx.match("[\\d_]+", "ab12_3c").text, "12_3")
    t.eq(rx.match("\\p{L}+", "123привет456").text, "привет")
    t.eq(rx.match("[[:alpha:]]+", "12ab34").text, "ab")
    t.eq(rx.match(".", "é").text, "é")
    t.eq(u8.len(rx.match("..", "😀😀").text), 2)
  end)
  t.it("anchors, flags, lookaround", function()
    local re = assert(rx.compile("^\\w+$", "m"))
    t.eq(#re:find_all("one\ntwo\nthree"), 3)
    t.truthy(rx.compile("hello", "i"):test("HeLLo"))
    t.truthy(rx.compile("a.b", "s"):test("a\nb")); t.falsy(rx.test("a.b", "a\nb"))
    t.eq(rx.match("\\bcat\\b", "a cat sat").start, 3); t.falsy(rx.test("\\bcat\\b", "concat"))
    t.eq(rx.match("\\d+(?=px)", "10em 20px").text, "20")
    t.eq(rx.match("\\d+(?!\\d|px)", "20px 30em").text, "30")
    t.eq(rx.match("(?<=\\$)\\d+", "cost $45").text, "45")
    t.eq(rx.match("(?<!\\$)\\b\\d+", "$45 67").text, "67")
    t.truthy(rx.compile("a b # comment\n c", "x"):test("abc"))
    t.truthy(rx.test("(?i)abc", "ABC"))
  end)
  t.it("gsub, split, gmatch", function()
    t.eq((rx.gsub("(\\w+)@(\\w+)", "a@b c@d", "$2 at $1")), "b at a d at c")
    t.eq((rx.gsub("\\d", "a1b2", function(m) return "<" .. m.text .. ">" end)), "a<1>b<2>")
    t.eq((rx.gsub("cat|dog", "cat dog bird", { cat = "CAT" })), "CAT dog bird")
    t.eq({ rx.gsub("x*", "abc", "-") }, { "-a-b-c-", 4 })
    t.eq((rx.gsub("(?<w>\\w+)", "hi yo", "${w}!")), "hi! yo!")
    t.eq((rx.gsub("a", "aaa", "b", 2)), "bba")
    t.eq(rx.split("\\s*,\\s*", "a , b,c ,d"), { "a", "b", "c", "d" })
    t.eq(rx.split(",", "a,b,c", 2), { "a", "b,c" })
    local words = {}; for m in rx.gmatch("\\w+", "one two  three") do words[#words + 1] = m.text end
    t.eq(words, { "one", "two", "three" })
    t.eq(rx.escape("a.b*c"), "a\\.b\\*c")
  end)
  t.it("errors and limits", function()
    local re, err = rx.compile("(abc"); t.is_nil(re); t.matches(err, "missing")
    t.is_nil((rx.compile("[z-a]")))
    t.is_nil((rx.compile("*a")))
    t.is_nil((rx.compile("\\2(a)")))
    t.throws(function() rx.test("(a*)*b", string.rep("a", 40) .. "c") end, "too complex")
  end)
end)

