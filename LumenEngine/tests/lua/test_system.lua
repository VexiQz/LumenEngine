t.describe("noise", function()
  t.it("stays in range and is continuous", function()
    for _, f in ipairs { noise.perlin3, noise.simplex3, noise.value3 } do
      local lo, hi = 1e9, -1e9
      for i = 1, 400 do
        local v = f(i * 0.37, i * 0.11, i * 0.23)
        lo, hi = math.min(lo, v), math.max(hi, v)
        t.truthy(math.abs(f(i * 0.37 + 1e-4, i * 0.11, i * 0.23) - v) < 0.01)
      end
      t.truthy(lo >= -1.01 and hi <= 1.01 and hi - lo > 0.3)
    end
    t.eq(noise.perlin2(1.5, 2.5, 3), noise.perlin2(1.5, 2.5, 3))
    t.neq(noise.simplex2(1.5, 2.5, 1), noise.simplex2(1.5, 2.5, 2))
  end)
  t.it("worley / fbm / grid / curl", function()
    local f1, f2 = noise.worley2(0.5, 0.5)
    t.truthy(f1 <= f2 and f1 >= 0)
    for _, mode in ipairs { "fbm", "ridged", "billow", "turbulence" } do
      local v = noise.fbm("simplex", 1.3, 2.1, 0, { octaves = 5, mode = mode })
      t.truthy(v > -1.5 and v < 1.5)
    end
    t.throws(function() noise.fbm("nope", 0, 0) end, "unknown noise")
    local g = noise.grid("perlin", 8, 4, 0.1); t.eq(#g, 32)
    t.eq(noise.curl2(0.3, 0.4).x, noise.curl2(0.3, 0.4).x)
  end)
end)

