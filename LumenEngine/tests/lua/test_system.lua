t.describe("net / http", function()
  t.it("tcp echo", function()
    local srv = assert(net.tcp_listen("127.0.0.1", 0))
    local _, port = srv:sockname()
    t.truthy(port > 0)
    local cli = assert(net.tcp_connect("127.0.0.1", port, 2))
    srv:settimeout(2)
    local conn, host = assert(srv:accept())
    conn:settimeout(2); cli:settimeout(2)
    assert(cli:send("hello\nworld\n"))
    t.eq(conn:recv_line(), "hello"); t.eq(conn:recv_line(), "world")
    assert(conn:send("abcdef")); t.eq(cli:recv_exact(4), "abcd"); t.eq(cli:recv(), "ef")
    conn:settimeout(0.05); local d, err = conn:recv(); t.is_nil(d); t.eq(err, "timeout")
    local r = net.select({ conn }, {}, 0.05); t.eq(#r, 0)
    cli:send("x"); r = net.select({ conn }, {}, 1); t.eq(#r, 1)
    cli:close(); conn:settimeout(1); conn:recv(); local d2, e2 = conn:recv(); t.eq(e2, "closed")
    t.falsy(cli:is_open()); srv:close()
  end)
  t.it("udp", function()
    local a = assert(net.udp_open("127.0.0.1", 0)); local b = assert(net.udp_open("127.0.0.1", 0))
    local _, pa = a:sockname()
    b:send_to("ping", "127.0.0.1", pa)
    a:settimeout(2)
    local data, host, port = a:recv_from()
    t.eq(data, "ping"); t.eq(host, "127.0.0.1")
  end)
  t.it("resolve and refused connection", function()
    t.truthy(#net.resolve("localhost") >= 1); t.truthy(net.is_ip("::1")); t.falsy(net.is_ip("x"))
