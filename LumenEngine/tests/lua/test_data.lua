local t = require "lumen.test"
local json = require "lumen.json"
local hash = require "lumen.hash"
local compress = require "lumen.compress"
local zip = require "lumen.zip"

t.describe("json", function()
  t.it("round trips values", function()
    local v = { a = 1, b = { 1, 2, 3 }, c = "x\ny", d = true, e = 1.5, f = {} }
    local s = assert(json.encode(v))
    t.eq(json.decode(s), { a = 1, b = { 1, 2, 3 }, c = "x\ny", d = true, e = 1.5, f = {} })
  end)
  t.it("keeps integers and floats apart", function()
    local d = json.decode('[1, 2.5, 3e2, -0]')
    t.eq(math.type(d[1]), "integer")
    t.eq(math.type(d[2]), "float")
    t.eq(d[3], 300.0)
  end)
  t.it("sorts keys deterministically and honours indent", function()
    t.eq(json.encode({ b = 1, a = 2 }), '{"a":2,"b":1}')
    t.eq(json.encode({ a = { 1 } }, { indent = 2 }), '{\n  "a": [\n    1\n  ]\n}')
  end)
  t.it("distinguishes arrays from objects", function()
    t.eq(json.encode({}), "[]")
    t.eq(json.encode(json.object()), "{}")
    t.eq(json.encode({ [1] = "a", [3] = "c" }), '{"1":"a","3":"c"}')
  end)
  t.it("reports parse errors", function()
    local v, err = json.decode('{"a": }')
    t.is_nil(v)
    t.matches(err, "1:")
  end)
  t.it("supports comments and trailing commas when asked", function()
    t.eq(json.decode('{"a":1, // hi\n"b":[1,],}', { comments = true, trailing_commas = true }), { a = 1, b = { 1 } })
    t.is_nil(json.decode('{"a":1,}'))
  end)
  t.it("handles null", function()
    t.eq(json.decode('{"a":null}'), {})
    t.eq(json.decode('{"a":null}', { keep_null = true }).a, json.null)
    t.eq(json.encode({ json.null }), "[null]")
  end)
  t.it("refuses cycles, NaN and functions", function()
    local c = {}
    c.self = c
    t.is_nil(json.encode(c))
    t.is_nil(json.encode(0 / 0))
    t.is_nil(json.encode(print))
  end)
  t.it("escapes unicode on request", function()
    t.eq(json.encode("é", { ascii = true }), '"\\u00e9"')
    t.eq(json.decode('"\\u00e9\\ud83d\\ude00"'), "é😀")
  end)
  t.it("honours __tojson", function()
    local o = setmetatable({}, { __tojson = function() return { kind = "custom" } end })
    t.eq(json.encode(o), '{"kind":"custom"}')
  end)
end)

t.describe("hash", function()
  t.it("md5", function()
    t.eq(hash.md5(""), "d41d8cd98f00b204e9800998ecf8427e")
    t.eq(hash.md5("The quick brown fox jumps over the lazy dog"), "9e107d9d372bb6826bd81d3542a419d6")
  end)
  t.it("sha1", function()
    t.eq(hash.sha1("abc"), "a9993e364706816aba3e25717850c26c9cd0d89d")
    t.eq(hash.sha1(""), "da39a3ee5e6b4b0d3255bfef95601890afd80709")
  end)
  t.it("sha256", function()
    t.eq(hash.sha256("abc"), "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad")
  end)
  t.it("hmac", function()
    t.eq(hash.hmac("sha256", "key", "The quick brown fox jumps over the lazy dog"), "f7bc83f430538424b13298e6aa6fb143ef4d59a14946175997479dbc2d1a3cd8")
    t.eq(hash.hmac("md5", "key", "The quick brown fox jumps over the lazy dog"), "80070713463e7749b90c2dc24911e275")
    t.eq(hash.hmac("sha1", "key", "The quick brown fox jumps over the lazy dog"), "de7c9b85b8b78aa6bc8a7a36f70a90701c9db4d9")
  end)
  t.it("pbkdf2", function()
    t.eq(hash.pbkdf2("sha1", "password", "salt", 2, 20), "ea6c014dc72d6f8ccd1ed92ace1d41f0d8de8957")
    t.eq(hash.pbkdf2("sha256", "password", "salt", 1, 32), "120fb6cffcf8b32c43e7225256c4f837a86548c92ccc35480805987cb70be17b")
  end)
  t.it("crc32 / adler32 / fnv", function()
    t.eq(hash.crc32("123456789"), 0xCBF43926)
    t.eq(hash.adler32("Wikipedia"), 0x11E60398)
    t.type_is(hash.fnv1a64("x"), "number")
  end)
  t.it("base64", function()
    t.eq(hash.base64_encode("Man"), "TWFu")
    t.eq(hash.base64_encode("Ma"), "TWE=")
    t.eq(hash.base64_encode("M"), "TQ==")
    t.eq(hash.base64_encode("M", false, false), "TQ")
    t.eq(hash.base64_decode("TWFu"), "Man")
    t.eq(hash.base64_decode("TQ"), "M")
    local bin = {}
    for i = 0, 255 do bin[#bin + 1] = string.char(i) end
    bin = table.concat(bin)
    t.eq(hash.base64_decode(hash.base64_encode(bin)), bin)
    t.eq(hash.base64_decode(hash.base64_encode(bin, true), true), bin)
    t.is_nil(hash.base64_decode("@@@"))
  end)
  t.it("hex", function()
    t.eq(hash.hex_encode("\0\255a"), "00ff61")
    t.eq(hash.hex_decode("00FF61"), "\0\255a")
    t.is_nil(hash.hex_decode("abc"))
  end)
  t.it("random + uuid", function()
    t.eq(#hash.random_bytes(32), 32)
    t.matches(hash.uuid4(), "^%x%x%x%x%x%x%x%x%-%x%x%x%x%-4%x%x%x%-[89ab]%x%x%x%-%x+$")
    t.neq(hash.uuid4(), hash.uuid4())
    t.truthy(hash.equal("abc", "abc"))
    t.falsy(hash.equal("abc", "abd"))
  end)
end)

t.describe("compress", function()
  local function sample(n)
    local parts = {}
    for i = 1, n do parts[#parts + 1] = "line " .. i % 37 .. " of the sample text, repeated a lot\n" end
    return table.concat(parts)
  end
  t.it("deflate round trip at every level", function()
    local data = sample(2000)
    for _, level in ipairs { 0, 1, 4, 6, 9 } do
      local c = compress.deflate(data, level)
      t.eq(compress.inflate(c), data, "level " .. level)
      if level > 0 then t.truthy(#c < #data / 5, "should compress well at level " .. level) end
    end
  end)
  t.it("handles empty and tiny input", function()
    t.eq(compress.inflate(compress.deflate("")), "")
    t.eq(compress.inflate(compress.deflate("a")), "a")
    t.eq(compress.zlib_decompress(compress.zlib_compress("")), "")
  end)
  t.it("handles incompressible data", function()
    local random = require "lumen.random"
    local data = require("lumen.hash").random_bytes(100000)
    t.eq(compress.inflate(compress.deflate(data)), data)
    t.eq(compress.inflate(compress.deflate(data, 0)), data)
  end)
  t.it("long matches and far distances", function()
    local data = string.rep("abcdefghij", 20000) .. string.rep("z", 70000) .. string.rep("abcdefghij", 100)
    t.eq(compress.inflate(compress.deflate(data)), data)
  end)
  t.it("zlib and gzip containers", function()
    local data = sample(500)
    t.eq(compress.zlib_decompress(compress.zlib_compress(data)), data)
    t.eq(compress.gunzip(compress.gzip(data)), data)
    local z = compress.zlib_compress(data)
    local bad = z:sub(1, -2) .. string.char((z:byte(-1) + 1) % 256)
    t.is_nil(compress.zlib_decompress(bad))
  end)
  t.it("rejects garbage", function()
    t.is_nil(compress.inflate("this is not deflate data at all"))
    t.is_nil(compress.gunzip("nope"))
  end)
end)

t.describe("zip", function()
  t.it("creates and reads archives in memory", function()
    local w = zip.create()
    w:add("a.txt", "hello"):add("dir/b.txt", string.rep("x", 1000))
    local data = w:tostring()
    local r = assert(zip.open_memory(data))
    t.eq(r:read("a.txt"), "hello")
    t.eq(#r:read("dir/b.txt"), 1000)
    t.truthy(r:exists("a.txt"))
    t.falsy(r:exists("zzz"))
    t.eq(#r:list(), 2)
    t.is_nil(r:read("missing"))
  end)
  t.it("rejects unsafe entry names", function()
    local w = zip.create()
    t.throws(function() w:add("../evil", "x") end, "unsafe")
    t.throws(function() w:add("/abs", "x") end, "unsafe")
  end)
  t.it("round trips through the file system", function()
    local fs = require "lumen.fs"
    local dir = fs.make_temp_dir("ziptest")
    fs.write(fs.join(dir, "src/one.txt"), "1")
    fs.write(fs.join(dir, "src/sub/two.txt"), "22")
    local w = zip.create()
    t.eq(w:add_dir(fs.join(dir, "src")), 2)
    assert(w:save(fs.join(dir, "out.zip")))
    local r = assert(zip.open(fs.join(dir, "out.zip")))
    t.eq(r:extract_all(fs.join(dir, "ex")), 2)
    t.eq(fs.read(fs.join(dir, "ex/sub/two.txt")), "22")
    fs.remove_all(dir)
  end)
end)

os.exit(t.run() and 0 or 1)
