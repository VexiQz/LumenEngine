// Lumen Engine — first launch bootstrap of the runtime folder.
//
// On the first start the engine creates `lumen_runtime/` next to its executable and fills it with the
// runtime it ships: the Lua standard library of the engine, LSP API definitions, native module headers
// (lumen_c.h / lumen.hpp), the shader library, project templates and documentation. Everything the
// engine needs afterwards (compiled Lua cache, shader cache, downloaded packages, logs, toolchain
// information) lives there too, so the engine directory is the only place that must be writable.
//
// Files are tracked in `runtime.json`: a file the user did not touch is updated silently when a newer
// engine ships a newer version; a file the user edited is kept and the new version is stored beside it
// as `<name>.lumen-new`.
#pragma once

#include "lumen/core/Common.h"
#include "lumen/core/Json.h"

namespace lumen
{
	// One file of the runtime payload, normally generated by `lumen embed` and linked into the binaries.
	struct EmbeddedFile
	{
		const char* path;       // relative to lumen_runtime, '/' separated
		const uint8_t* data;
		uint64_t size;
		uint64_t hash;          // FNV-1a 64 of the content
	};

	struct EmbeddedTable
	{
		const EmbeddedFile* files = nullptr;
		size_t count = 0;
	};

	struct RuntimeLayout
	{
		std::string root;         // <exe>/lumen_runtime
		std::string lua;          // Lua standard library of the engine (required via package.path)
		std::string luaApi;       // EmmyLua definitions (lumen.lua, wicked.lua) for language servers
		std::string luaCache;     // compiled bytecode cache
		std::string include;      // lumen_c.h, lumen.hpp for native game modules
		std::string shaders;      // Lumen shader library (HLSL includes and material shaders)
		std::string shaderCache;  // compiled shader cache
		std::string templates;    // project templates
		std::string packages;     // global package download cache
		std::string imports;      // import cache (converted models, textures)
		std::string logs;
		std::string config;       // engine.json, registry.json, toolchain.json
		std::string toolchain;    // downloaded / located build tools
		std::string docs;
		std::string tmp;
	};

	struct RuntimeInfo
	{
		RuntimeLayout layout;
		bool firstRun = false;
		bool usedUserDataFallback = false; // exe directory was not writable
		int filesInstalled = 0;
		int filesUpdated = 0;
		int filesKeptModified = 0;
		std::string engineVersion;
		std::string exeDir;
	};

	struct RuntimeOptions
	{
		std::string explicitRoot;                 // overrides everything (also: env LUMEN_RUNTIME_DIR)
		EmbeddedTable embedded;                   // payload to install
		std::vector<std::string> sourceDirs;      // development: copy payload from these directories instead / in addition
		bool allowUserDataFallback = true;
		bool installLogFile = true;               // adds a rotating file log sink in logs/
		std::string logName = "lumen";
	};

	class Runtime
	{
	public:
		// Creates/updates the runtime folder. Safe to call on every start; cheap when nothing changed.
		static Status Initialize(const RuntimeOptions& options);
		static bool IsInitialized();
		static const RuntimeInfo& Info();
		static const RuntimeLayout& Layout() { return Info().layout; }

		// config/engine.json — user level engine settings. Missing keys fall back to built-in defaults.
		static Json& Config();
		static Status SaveConfig();

		// Verifies installed files against the manifest and restores missing/damaged ones.
		static Status Repair(const EmbeddedTable& embedded, int* restored = nullptr);
	};

} // namespace lumen
